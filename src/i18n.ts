export type TranslationKey = keyof typeof translations.en;

export function t(key: TranslationKey, lang: Language = 'en'): string {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

export function getTradeLabel(
  trade: TradeId,
  lang: Language,
  customTradeName?: string
): string {
  if (trade === 'other' && customTradeName && customTradeName.trim()) {
    return customTradeName.trim();
  }
  const key = `trade_${trade}` as TranslationKey;
  return t(key, lang);
}

export function getGovtIdLabel(idType: GovtIdType, lang: Language): string {
  const key = `govtId_${idType}` as TranslationKey;
  return t(key, lang);
}

export function getRateUnitLabel(unit: RateUnit, lang: Language): string {
  if (unit === 'hour') return t('perHour', lang);
  if (unit === 'day') return t('perDay', lang);
  return t('perJob', lang);
}

export function getSlotLabel(slotId: TimeSlotId, lang: Language): string {
  const found = TIME_SLOTS.find((s) => s.id === slotId);
  if (!found) return slotId;
  return lang === 'hi' ? found.labelHi : found.labelEn;
}

export function getIssueTagLabel(tag: IssueTagId, lang: Language): string {
  return t(`issue_${tag}` as TranslationKey, lang);
}

export function getLikeTagLabel(tag: LikeTagId, lang: Language): string {
  return t(`like_${tag}` as TranslationKey, lang);
}

export function getRefereeRelationLabel(rel: RefereeRelation, lang: Language): string {
  return t(`rel_${rel}` as TranslationKey, lang);
}
